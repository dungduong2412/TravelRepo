#!/usr/bin/env node
// READ-ONLY audit-gap analysis for the Merchant-member audit-atomicity remediation. It CHANGES NOTHING.
//
//   Hosted (the live project):  railway run --service vno-api -- node migration/v2/analyze-member-audit-gaps.mjs [--out <dir>]
//   Disposable rehearsal DB:    node migration/v2/analyze-member-audit-gaps.mjs --rehearsal --key <service-role JWT> [--out <dir>]
//
// Read-only by construction: the only network primitive in this file is get() (HTTP GET against PostgREST); there is no code path that sends another method.
// It refuses to run against any host except the live Supabase project (or loopback with --rehearsal).
// Privacy: it selects only identifiers, status, dates and the e-mail (which is hashed in memory immediately and never printed or written); no name, phone or bank
// field is read. Output = counts plus identifiers (ids / codes) of rows that may need MANUAL investigation.
//
// Question answered: which pending Merchant "member" applications have NO creation audit event (candidates for MANUAL investigation: the new API refuses to
// replay such an application and writes nothing), and what does the data say about a database uniqueness constraint and durable throttling?
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const args = process.argv.slice(2);
const rehearsal = args.includes('--rehearsal');
const arg = (name) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : undefined; };
const HOSTED_HOST = 'hsezyogfxgnkpweoqqny.supabase.co';
const die = (m) => { console.error(`FATAL: ${m}`); process.exit(1); };

let base; let key;
if (rehearsal) {
  base = process.env.VNO_REHEARSAL_REST || 'http://localhost:54998'; key = arg('--key') || '';
  if (!/^http:\/\/(localhost|127\.0\.0\.1):\d+$/.test(base)) die('--rehearsal requires a loopback PostgREST');
} else {
  const u = process.env.SUPABASE_URL; key = process.env.SUPABASE_SERVICE_ROLE_KEY || '';
  if (!u || !key) die('SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY are not set (run it through `railway run --service vno-api -- node ...`)');
  if (new URL(u).hostname !== HOSTED_HOST) die(`refusing to run: ${new URL(u).hostname} is not the live project ${HOSTED_HOST}`);
  base = `${u.replace(/\/$/, '')}/rest/v1`;
}
if (!key) die('no service key');

// ---- the ONLY network primitive: GET ------------------------------------------------------------------------------------------------------------------
async function get(path) {
  const res = await fetch(`${base}/${path}`, { method: 'GET', headers: { apikey: key, authorization: `Bearer ${key}`, accept: 'application/json' } });
  if (!res.ok) die(`GET ${path.split('?')[0]} -> HTTP ${res.status}`);
  return res.json();
}
async function getAll(table, select, filter = '', order = 'id.asc') {
  const out = []; const page = 1000;
  for (let offset = 0; ; offset += page) {
    const rows = await get(`${table}?select=${encodeURIComponent(select)}${filter ? `&${filter}` : ''}&order=${order}&limit=${page}&offset=${offset}`);
    out.push(...rows); if (rows.length < page) break;
  }
  return out;
}

const CREATED = 'collaborator.member_application_created';
const MEMBERS_CODE = /^COL[0-9A-F]{7}$/;            // the code shape generated by POST /merchants/members
const sha = (s) => createHash('sha256').update(String(s).trim().toLowerCase()).digest('hex');
const countBy = (xs, f) => xs.reduce((m, x) => { const k = f(x); m[k] = (m[k] || 0) + 1; return m; }, {});
const shapeOf = (code) => MEMBERS_CODE.test(code || '') ? 'COL+7hex (Merchant Members API)' : /^COL-[0-9A-F]{16}$/.test(code || '') ? 'COL-+16hex (registration / Admin / V1)' : code ? 'other' : 'no code';

const collab = await getAll('collaborators', 'id,merchant_system_id,collaborators_code,collaborators_status,collaborators_verified,collaborators_registered_date,collaborators_email');
const events = await getAll('audit_events', 'id,entity_id,action,occurred_at,actor_role,merchant:details->>merchant_id', `action=eq.${CREATED}`);
const profiles = await getAll('user_profiles', 'id,collaborator_id', 'collaborator_id=not.is.null');

const byEntity = new Map();
for (const e of events) { const m = byEntity.get(e.entity_id) || { created: 0 }; m.created += 1; byEntity.set(e.entity_id, m); }
const hasLogin = new Set(profiles.map((p) => p.collaborator_id));
const ids = new Set(collab.map((c) => c.id));

// ---- A. which applications have no creation audit --------------------------------------------------------------------------------------------------------
const pendingAssigned = collab.filter((c) => c.collaborators_status === 'pending' && c.collaborators_verified !== true && c.merchant_system_id);
const audited = (c) => { const m = byEntity.get(c.id); return !!m && m.created > 0; };
const memberShaped = collab.filter((c) => MEMBERS_CODE.test(c.collaborators_code || ''));
const gaps = memberShaped.filter((c) => !audited(c));
const gapsPending = gaps.filter((c) => c.collaborators_status === 'pending' && c.collaborators_verified !== true);

// ---- B. audit events that do not line up with a row -------------------------------------------------------------------------------------------------------
const orphanEvents = [...byEntity.keys()].filter((id) => !ids.has(id));
const multiCreated = [...byEntity.entries()].filter(([, m]) => m.created > 1).map(([id]) => id);

// ---- C. e-mail duplicates (the input for a database uniqueness decision) ------------------------------------------------------------------------------------
const groups = new Map();
for (const c of collab) { if (!c.collaborators_email) continue; const h = sha(c.collaborators_email); (groups.get(h) || groups.set(h, []).get(h)).push(c); }
const dupGroups = [...groups.values()].filter((g) => g.length > 1);
const dupInfo = dupGroups.map((g) => ({
  size: g.length, merchants: new Set(g.map((c) => c.merchant_system_id || 'none')).size, statuses: [...new Set(g.map((c) => c.collaborators_status || 'null'))].sort().join('+'),
  involvesMembersShaped: g.some((c) => MEMBERS_CODE.test(c.collaborators_code || '')), pendingOnly: g.every((c) => c.collaborators_status === 'pending'),
}));
const pendingDupGroups = [...groups.values()].filter((g) => g.filter((c) => c.collaborators_status === 'pending').length > 1);

// ---- D. usage and throttling history (created events carry the Merchant id) ---------------------------------------------------------------------------------
const created = events.filter((e) => e.action === CREATED);
const perMerchantHour = {}; const perMerchantDay = {};
for (const e of created) {
  if (!e.merchant) continue; const hour = e.occurred_at.slice(0, 13); const day = e.occurred_at.slice(0, 10);
  const kh = `${e.merchant}|${hour}`; const kd = `${e.merchant}|${day}`; perMerchantHour[kh] = (perMerchantHour[kh] || 0) + 1; perMerchantDay[kd] = (perMerchantDay[kd] || 0) + 1;
}
const pendingPerMerchant = countBy(pendingAssigned, (c) => c.merchant_system_id);
const maxOf = (o) => Math.max(0, ...Object.values(o));

const summary = {
  generated_at: new Date().toISOString(), target: rehearsal ? 'LOCAL REHEARSAL DATABASE' : `live project ${HOSTED_HOST}`, read_only: true,
  collaborators: {
    total: collab.length, by_status: countBy(collab, (c) => c.collaborators_status || 'null'), by_code_shape: countBy(collab, (c) => shapeOf(c.collaborators_code)),
    with_merchant_system_id: collab.filter((c) => c.merchant_system_id).length, linked_to_a_login: collab.filter((c) => hasLogin.has(c.id)).length,
  },
  audit: {
    created_events: created.length, created_by_actor_role: countBy(created, (e) => e.actor_role || 'null'),
    entities_with_events: byEntity.size, orphan_events_entity_missing: orphanEvents.length, entities_with_more_than_one_created_event: multiCreated.length,
  },
  manual_investigation_candidates: {
    members_api_shaped_rows: memberShaped.length, of_which_without_a_creation_event: gaps.length,
    of_which_still_pending_and_unverified: gapsPending.length,
    pending_with_merchant_id_total: pendingAssigned.length, pending_with_merchant_id_without_event: pendingAssigned.filter((c) => !audited(c)).length,
    pending_with_merchant_id_without_event_by_code_shape: countBy(pendingAssigned.filter((c) => !audited(c)), (c) => shapeOf(c.collaborators_code)),
    candidate_rows: gaps.map((c) => ({ id: c.id, code: c.collaborators_code, status: c.collaborators_status, verified: c.collaborators_verified, registered: c.collaborators_registered_date, linked_to_a_login: hasLogin.has(c.id) })),
  },
  email_duplicates: {
    rows_with_email: [...groups.values()].reduce((n, g) => n + g.length, 0), distinct_emails: groups.size, duplicate_groups: dupGroups.length,
    rows_in_duplicate_groups: dupGroups.reduce((n, g) => n + g.length, 0), group_size_histogram: countBy(dupInfo, (g) => g.size),
    groups_by_status_mix: countBy(dupInfo, (g) => g.statuses), groups_spanning_more_than_one_merchant: dupInfo.filter((g) => g.merchants > 1).length,
    groups_involving_members_api_rows: dupInfo.filter((g) => g.involvesMembersShaped).length, groups_with_more_than_one_pending_row: pendingDupGroups.length,
    groups_entirely_pending: dupInfo.filter((g) => g.pendingOnly).length,
  },
  throttling_history: {
    pending_per_merchant_max: maxOf(pendingPerMerchant), merchants_with_pending_at_or_above_40: Object.values(pendingPerMerchant).filter((n) => n >= 40).length,
    merchants_at_or_above_cap_50: Object.values(pendingPerMerchant).filter((n) => n >= 50).length,
    max_creations_one_merchant_one_hour: maxOf(perMerchantHour), max_creations_one_merchant_one_day: maxOf(perMerchantDay),
    hours_over_10: Object.values(perMerchantHour).filter((n) => n > 10).length, days_over_40: Object.values(perMerchantDay).filter((n) => n > 40).length,
    created_events_by_day: countBy(created, (e) => e.occurred_at.slice(0, 10)),
  },
  // identifiers only (no name / phone / e-mail / bank field is ever read) so the owner can review each row
  pending_with_merchant_id_without_event_rows: pendingAssigned.filter((c) => !audited(c)).map((c) => ({ id: c.id, code: c.collaborators_code, registered: c.collaborators_registered_date, linked_to_a_login: hasLogin.has(c.id) })),
  email_duplicate_groups_rows: dupGroups.slice(0, 100).map((g, i) => ({ group: i + 1, rows: g.map((c) => ({ id: c.id, code: c.collaborators_code, status: c.collaborators_status ?? null, verified: c.collaborators_verified ?? null, has_merchant_id: !!c.merchant_system_id, linked_to_a_login: hasLogin.has(c.id), registered: c.collaborators_registered_date })) })),
  orphan_event_entities: orphanEvents.slice(0, 200), multi_created_entities: multiCreated.slice(0, 200),
};

const out = resolve(arg('--out') || (rehearsal ? '/tmp/members-audit-gaps-rehearsal' : join(new URL('../../', import.meta.url).pathname, 'migration/v2/evidence/members-audit-gaps-20261111-rev2')));
mkdirSync(out, { recursive: true, mode: 0o700 });
writeFileSync(join(out, 'summary.json'), JSON.stringify(summary, null, 2), { mode: 0o600 });
const { candidate_rows, ...printable } = summary.manual_investigation_candidates;
const { pending_with_merchant_id_without_event_rows, email_duplicate_groups_rows, ...printSummary } = summary;
console.log(JSON.stringify({ ...printSummary, manual_investigation_candidates: { ...printable, candidate_rows: `${candidate_rows.length} rows listed in summary.json` }, orphan_event_entities: `${orphanEvents.length}`, multi_created_entities: `${multiCreated.length}`, rows_listed_in_summary_json: { pending_with_merchant_id_without_event: pending_with_merchant_id_without_event_rows.length, email_duplicate_groups: email_duplicate_groups_rows.length } }, null, 2));
console.log(`\nREAD-ONLY. Nothing was changed. Evidence (identifiers and counts only; no name, phone, e-mail or bank data): ${out}/summary.json`);
